"""Plain-language report of the 180 priority ACs: which are done and why each of the others is not.

    python batch/status_report.py [--out queue/priority_180_report.md]

Reads queue/priority_180_status.csv (written by batch/priority_status.py), queue/split_report.csv and
data/2024/PDF/missing_AC.md and writes a markdown file. Nothing is recomputed here, so run priority_status.py first
for current numbers.
"""
import argparse
import re
import sys
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from queue_common import DEFAULT_DATA_ROOT, QUEUE_DIR, read_csv  # noqa: E402

GROUPS = ("Eng single-file", "Hin single-file", "Duplicate PDFs")
SHEET_UNDER_OTHER_NUMBER = 190       # 109Eng.pdf is really the Lambhua sheet, i.e. AC 190
STATES = ("DONE (verified)", "CONVERTED, NOT VERIFIED", "FAILED", "ON HOLD", "NOT ATTEMPTED")

# reason prefix -> (heading, what it means, what happens next)
CAUSES = (
    ("Read exactly", "Read exactly from the PDF, official differs by a few votes",
     "The PDF has a text layer, so every digit is exact, and the workbook has the same numbers as the PDF. Its column totals "
     "differ from the official 2024 data by a few votes, which points to a typo in the sheet or in the official data.",
     "Spot-check the few rows involved; if the PDF is right, the workbook can be used as it is."),
    ("Nearly right", "Nearly right",
     "Every booth row was found; a few digits are misread, so the column totals are off by under 3%.",
     "Re-read the uncertain cells; whatever is still uncertain goes to a human review sheet."),
    ("PDF holds several", "Several constituencies in one PDF",
     "The PDF contains more than one constituency, or the grid was split into too many columns.",
     "Cut the PDF into constituencies at the official running totals (done for 137Eng and 141Eng)."),
    ("Sheet's own total", "Total rows read as booths",
     "The sheet's own sub-total / grand-total rows were counted as polling booths, so the votes are doubled or tripled.",
     "Fixed in the extractor (total rows are now dropped); needs a re-run."),
    ("Rows/pages missed", "Pages or rows missed",
     "The table was not found on some pages (a short last page, a skewed or photographed page), so those booths are missing.",
     "Short last pages are fixed; the rest needs a sturdier table finder for skewed and photographed pages."),
    ("Extra/duplicated", "Extra or duplicated rows",
     "Pages repeated in the PDF, or extra columns were detected, so there are more votes than the official total.",
     "Duplicate pages are now dropped and the column count is fixed from the official candidate count; needs a re-run."),
    ("Digits misread", "Many digits misread",
     "Rows were read but too many digits are wrong. Usually the cell grid was a little off on some pages, not a blurry scan.",
     "Re-run with the grid-alignment and row-repair fixes; the rest goes to the review sheet."),
    ("Table found but", "Could not read the table reliably",
     "The table was found but the first pages did not read cleanly enough to continue. Often the layout is unusual rather than the scan being poor.",
     "Check the layout of each file (column order, id columns) and re-run; scans that stay unreadable go to manual review."),
    ("Could not find", "Table columns not found",
     "The vertical column lines are too faint or uneven to detect.",
     "Build a table finder that works from the ink instead of ruled lines."),
    ("Different form layout", "Portrait-page layout",
     "These PDFs use a different (portrait) page layout that the tool does not read yet.",
     "Write an adapter for the portrait layout."),
    ("Not run yet", "Not run yet", "Not attempted so far.", "Run it."),
)


def cause_of(reason):
    for prefix, heading, meaning, nxt in CAUSES:
        if reason.startswith(prefix):
            return heading, meaning, nxt
    return reason, reason, ""


def missing_acs(md_path):
    """AC numbers in the 'Missing ACs' paragraph of missing_AC.md."""
    text = Path(md_path).read_text(encoding="utf-8")
    m = re.search(r"## Missing ACs.*?\n(.*?)(?=\n## )", text, re.S)
    return sorted({int(x) for x in re.findall(r"\b\d+\b", m.group(1))}) if m else []


def short_list(acs):
    return ", ".join(str(a) for a in sorted(acs)) or "none"


def render(rows, splits, missing, today=None):
    """rows: priority_180_status.csv rows; splits: split_report.csv rows; missing: AC numbers without a PDF."""
    today = today or date.today().isoformat()
    by_state = defaultdict(list)
    for r in rows:
        by_state[r["state"]].append(r)
    out = [f"# Form 20 conversion: the {len(rows)} priority ACs", "",
           f"Status on {today}. Generated by `batch/status_report.py` from `queue/priority_180_status.csv`; "
           "re-run `batch/priority_status.py` and then this script to refresh it.", "",
           "**Done (verified)** means the Excel file's candidate columns and NOTA add up exactly to the official 2024 "
           "EVM totals for that constituency. Anything else is not counted as done, even when it looks close.", "",
           "## Summary", "", "| | " + " | ".join(GROUPS) + " | All |", "|---|" + "---|" * (len(GROUPS) + 1)]
    for state in STATES:
        cells = [sum(1 for r in by_state[state] if r["group"] == g) for g in GROUPS]
        out.append(f"| {state.capitalize()} | " + " | ".join(map(str, cells)) + f" | **{sum(cells)}** |")
    totals = [sum(1 for r in rows if r["group"] == g) for g in GROUPS]
    out += [f"| **Total** | " + " | ".join(map(str, totals)) + f" | **{sum(totals)}** |", ""]

    done = by_state["DONE (verified)"]
    out += [f"## Done and verified ({len(done)})", "",
            "Verified workbooks are copied to `Shakkti_Form20_Extraction/data/output/staged_excel/<AC>.xlsx`, in the "
            "same layout as `data/2024/EXCEL`. Nothing has been written into `data/2024/EXCEL` itself.", ""]
    for g in GROUPS:
        sub = [r for r in done if r["group"] == g]
        out += [f"**{g}** ({len(sub)} of {sum(1 for r in rows if r['group'] == g)}): {short_list(int(r['ac']) for r in sub)}", ""]
    out += ["| AC | PDF | How it was confirmed |", "|---|---|---|"]
    out += [f"| {r['ac']} | {r['pdf_files']} | {r['reason']} |" for r in sorted(done, key=lambda r: int(r["ac"]))]
    out.append("")

    extra = [s for s in splits if s["verdict"] == "FULL" and int(s["ac"]) not in {int(r["ac"]) for r in rows}]
    if extra:
        out += ["### Also verified (not in the priority list)", "",
                "These ACs had no PDF of their own; their data was inside another constituency's PDF and was cut out "
                "of it by the official running totals:", ""]
        out += [f"- AC {s['ac']} (from {s['source']}, {s['booths']} booths)" for s in extra]
        out.append("")

    out += [f"## Not done yet ({len(rows) - len(done)})", ""]
    groups = defaultdict(list)
    for r in rows:
        if r["state"] != "DONE (verified)":
            heading, meaning, nxt = cause_of(r["reason"])
            groups[(heading, meaning, nxt)].append(r)
    for (heading, meaning, nxt), sub in sorted(groups.items(), key=lambda kv: -len(kv[1])):
        out += [f"### {heading} ({len(sub)})", "", f"- **What it means:** {meaning}", f"- **Next:** {nxt}",
                f"- **ACs:** {short_list(int(r['ac']) for r in sub)}", ""]
    out += ["Per-AC reason (the tool's automatic diagnosis, with the exact figures):", "",
            "| AC | Group | State | Reason |", "|---|---|---|---|"]
    out += [f"| {r['ac']} | {r['group']} | {r['state'].capitalize()} | {r['reason']} |"
            for r in sorted(rows, key=lambda r: int(r["ac"])) if r["state"] != "DONE (verified)"]
    out.append("")

    partial = [s for s in splits if s["verdict"] != "FULL"]
    recovered = {int(s["ac"]) for s in splits if s["verdict"] == "FULL"}
    left = [a for a in missing if a not in recovered and a != SHEET_UNDER_OTHER_NUMBER]
    out += [f"## ACs with no PDF of their own ({len(missing)} in missing_AC.md)", "",
            f"- Recovered and verified from another PDF: {short_list(a for a in missing if a in recovered)}",
            f"- Partly recovered, not verified: {short_list(int(s['ac']) for s in partial)} "
            "(cut from the same PDF, but only some candidate columns match the official totals)",
            f"- AC {SHEET_UNDER_OTHER_NUMBER} does have a PDF: `109Eng.pdf` is the Lambhua sheet, so it is counted as "
            f"{SHEET_UNDER_OTHER_NUMBER}, not 109.",
            f"- Still without a PDF of their own: {len(left)} ACs: {short_list(left)}", ""]
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Write the plain-language status report of the priority ACs.")
    ap.add_argument("--out", default=str(QUEUE_DIR / "priority_180_report.md"))
    args = ap.parse_args(argv)
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    rows = read_csv(QUEUE_DIR / "priority_180_status.csv")
    splits = read_csv(QUEUE_DIR / "split_report.csv")
    missing = missing_acs(Path(DEFAULT_DATA_ROOT) / "PDF" / "missing_AC.md")
    Path(args.out).write_text(render(rows, splits, missing), encoding="utf-8")
    print(f"wrote {args.out}: {dict(Counter(r['state'] for r in rows))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
