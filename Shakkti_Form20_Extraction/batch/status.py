"""Master status of all 403 ACs: what is done, verified, on hold, waiting for a decision or missing a PDF.

    python batch/status.py            # refreshes queue/status.md, queue/status.csv and queue/on_hold.csv

Reads data/2024/EXCEL, data/2024/PDF (names only), queue/conversion_ledger.csv, queue/official_check.csv (run
batch/verify_official.py first) and queue/to_review.csv. Read-only on the data folders.

States, best first:
  DONE_EXCEL            an Excel from the earlier converter already exists
  VERIFIED              OCR workbook; every candidate column and NOTA equal the official 2024 totals, no repair needed
  VERIFIED_REPAIRED     same, but some uncertain rows were settled against the official totals (less independent)
  CONVERTED_UNVERIFIED  OCR workbook exists but the official check does not match - needs review
  FAILED                the extractor could not read the PDF (on hold)
  NEEDS_DECISION        duplicate / quarantined / mislabelled PDFs waiting for a choice or a different converter
  NOT_RUN               has a PDF, queued, not attempted yet
  NO_PDF                no PDF in data/2024/PDF
"""
import argparse
import sys
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from build_queue import MAX_AC  # noqa: E402
from queue_common import DEFAULT_DATA_ROOT, QUEUE_DIR, ac_of, read_csv, write_csv  # noqa: E402

RANK = ["DONE_EXCEL", "VERIFIED", "VERIFIED_REPAIRED", "CONVERTED_UNVERIFIED", "FAILED", "NEEDS_DECISION", "NOT_RUN",
        "NO_PDF"]
USABLE = {"DONE_EXCEL", "VERIFIED", "VERIFIED_REPAIRED"}
STATUS_FIELDS = ["ac", "state", "file", "detail"]
HOLD_FIELDS = ["ac", "state", "file", "reason", "next_action"]
NEXT_ACTION = {
    "CONVERTED_UNVERIFIED": "review the flagged rows / repair against the official totals",
    "FAILED": "needs extractor work (column detection, row spacing or a new layout)",
    "NEEDS_DECISION": "choose the right copy or use another converter",
    "NOT_RUN": "run the converter",
    "NO_PDF": "source the PDF",
}


def ac_state(ac, excel_acs, pdf_acs, ledger_rows, official, review):
    """-> (state, file, detail) for one AC. ledger_rows: ledger rows of this AC; official: {file: check row};
    review: blocking to_review row of this AC or None. official: {workbook name: official-check row}."""
    if ac in excel_acs:
        return "DONE_EXCEL", "", "Excel exists in data/2024/EXCEL"
    best = None
    for r in ledger_rows:
        if r["status"] == "DONE":
            chk = official.get(Path(r["xlsx"]).name, {})     # the official check is keyed by workbook name
            if chk.get("verdict") == "FULL":
                repaired = int(r.get("repaired_rows") or 0) > 0
                cand = ("VERIFIED_REPAIRED" if repaired else "VERIFIED", r["file"],
                        f"{r['rows']} rows; {r['repaired_rows']} rows settled against official totals" if repaired
                        else f"{r['rows']} rows; every column equals the official total")
            else:
                why = chk.get("detail") or r.get("review_reason") or "official check does not match"
                cand = ("CONVERTED_UNVERIFIED", r["file"], f"{r['rows']} rows; {why[:140]}")
        else:
            cand = ("FAILED", r["file"], r["error"][:140])
        if best is None or RANK.index(cand[0]) < RANK.index(best[0]):
            best = cand
    if best:
        return best
    if review:
        return "NEEDS_DECISION", review["files"], f"{review['category']}: {review['suggested_action'][:120]}"
    if ac in pdf_acs:
        return "NOT_RUN", "", "queued, not attempted yet"
    return "NO_PDF", "", "no PDF in data/2024/PDF"


def build_status(excel_acs, pdf_acs, ledger, official, review_rows, max_ac=MAX_AC):
    by_ac = defaultdict(list)
    for r in ledger:
        by_ac[int(r["ac"])].append(r)
    blocking = {int(r["ac"]): r for r in review_rows if r["ac"] != "" and r["blocks_conversion"] == "yes"}
    rows = []
    for ac in range(1, max_ac + 1):
        state, file, detail = ac_state(ac, excel_acs, pdf_acs, by_ac.get(ac, []), official, blocking.get(ac))
        rows.append({"ac": ac, "state": state, "file": file, "detail": detail})
    return rows


def render_status_md(rows):
    n = Counter(r["state"] for r in rows)
    usable = sum(n[s] for s in USABLE)
    with_pdf = len(rows) - n["NO_PDF"]
    out = [
        "# Form 20 conversion status - all 403 ACs",
        "",
        f"Generated by `batch/status.py` on {datetime.now():%Y-%m-%d %H:%M}. Do not edit by hand.",
        "",
        f"**Usable now: {usable} of {len(rows)} ACs ({usable} of the {with_pdf} that have a PDF).**",
        "",
        "| State | ACs | Meaning |",
        "|---|---:|---|",
        f"| DONE_EXCEL | {n['DONE_EXCEL']} | Excel from the earlier converter already exists |",
        f"| VERIFIED | {n['VERIFIED']} | OCR workbook; every candidate column and NOTA equal the official 2024 totals |",
        f"| VERIFIED_REPAIRED | {n['VERIFIED_REPAIRED']} | same, after settling uncertain rows against the official totals |",
        f"| CONVERTED_UNVERIFIED | {n['CONVERTED_UNVERIFIED']} | OCR workbook exists but does not match the official totals - needs review |",
        f"| FAILED | {n['FAILED']} | extractor could not read the PDF - on hold |",
        f"| NEEDS_DECISION | {n['NEEDS_DECISION']} | duplicate / quarantined / unsupported-layout PDFs waiting for a choice or another converter |",
        f"| NOT_RUN | {n['NOT_RUN']} | has a PDF, not attempted yet |",
        f"| NO_PDF | {n['NO_PDF']} | no PDF in data/2024/PDF - cannot be converted |",
        "",
    ]
    for state in ("VERIFIED", "VERIFIED_REPAIRED", "CONVERTED_UNVERIFIED", "NEEDS_DECISION", "NOT_RUN", "FAILED", "NO_PDF"):
        acs = [r["ac"] for r in rows if r["state"] == state]
        out += [f"## {state} ({len(acs)})", "", ", ".join(map(str, acs)) or "none", ""]
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description="Master status of all 403 ACs.")
    ap.add_argument("--data-root", default=str(DEFAULT_DATA_ROOT))
    ap.add_argument("--queue-dir", default=str(QUEUE_DIR))
    args = ap.parse_args(argv)
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    root, qd = Path(args.data_root), Path(args.queue_dir)

    overrides = {r["file"]: int(r["ac"]) for r in read_csv(qd / "ac_overrides.csv")}
    excel_acs = {ac_of(p.name) for p in (root / "EXCEL").glob("*.xlsx")} - {None}
    pdf_acs = {overrides.get(p.name, ac_of(p.name)) for p in (root / "PDF").glob("*.pdf")} - {None}
    ledger = read_csv(qd / "conversion_ledger.csv")
    official = {r["file"]: r for r in read_csv(qd / "official_check.csv")}   # workbook name -> check row
    rows = build_status(excel_acs, pdf_acs, ledger, official, read_csv(qd / "to_review.csv"))
    for sp in read_csv(qd / "split_report.csv"):                 # ACs delivered by splitting a multi-constituency PDF
        r = rows[int(sp["ac"]) - 1]
        if sp["verdict"] == "FULL" and r["state"] not in USABLE:
            r.update(state="VERIFIED", file=sp["source"], detail=f"split from {sp['source']}; every column equals the official total")

    write_csv(qd / "status.csv", STATUS_FIELDS, rows)
    (qd / "status.md").write_text(render_status_md(rows), encoding="utf-8")
    hold = [{"ac": r["ac"], "state": r["state"], "file": r["file"], "reason": r["detail"],
             "next_action": NEXT_ACTION[r["state"]]} for r in rows if r["state"] in NEXT_ACTION and r["state"] != "NOT_RUN"]
    write_csv(qd / "on_hold.csv", HOLD_FIELDS, hold)
    n = Counter(r["state"] for r in rows)
    print({s: n[s] for s in RANK if n[s]})
    print(f"usable {sum(n[s] for s in USABLE)} of {len(rows)}; written to {qd}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
